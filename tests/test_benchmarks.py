ROOT = Path(__file__).resolve().parents[1]


def test_benchmark_harness_records_samples_and_human_summary(tmp_path: Path) -> None:
    calls = []

    def operation() -> BenchmarkObservation:
        calls.append(len(calls))
        payload = bytes(range(64))
        return BenchmarkObservation(output_bytes=len(payload))

    run = run_benchmarks(
        (
            BenchmarkCase(
                id="passing",
                category="test",
                description="A deterministic passing workload.",
                implementation="test double",
                fixture="generated bytes",
                operation=operation,
                warmup_iterations=2,
                measured_iterations=3,
            ),
        ),
        run_id="test-run",
        git_commit="abc123",
    )

    case = run.cases[0]
    assert len(calls) == 5
    assert case.status == BenchmarkStatus.PASSED
    assert case.measured_iterations == 3
    assert len(case.samples) == 3
    assert {sample.output_bytes for sample in case.samples} == {64}
    assert case.min_ms is not None
    assert case.median_ms is not None
    assert case.p95_ms is not None
    assert case.peak_python_bytes is not None
    assert case.process_peak_rss_bytes is not None

    json_path = tmp_path / "run.json"
    summary_path = tmp_path / "run.md"
    write_benchmark_run(run, json_path, summary_path)
    assert BenchmarkRun.model_validate_json(json_path.read_text()) == run
    assert "| passing | test double | passed |" in summary_path.read_text()


def test_benchmark_harness_reports_skip_and_failure_without_hiding_suite() -> None:
    def skip() -> BenchmarkObservation:
        raise BenchmarkSkip("optional tool missing")

    def fail() -> BenchmarkObservation:
        raise RuntimeError("broken operation")

    run = run_benchmarks(
        (
            BenchmarkCase("skip", "test", "skip", "test", "none", skip),
            BenchmarkCase("fail", "test", "fail", "test", "none", fail),
        ),
        run_id="nonpassing",
        git_commit="abc123",
    )

    assert [case.status for case in run.cases] == [
        BenchmarkStatus.SKIPPED,
        BenchmarkStatus.FAILED,
    ]
    assert run.cases[0].error == "optional tool missing"
    assert run.cases[1].error == "RuntimeError: broken operation"
    assert all(case.samples == () for case in run.cases)


def test_budgets_are_derived_from_and_bound_to_the_measured_run(tmp_path: Path) -> None:
    run = run_benchmarks(
        (
            BenchmarkCase(
                "budgeted",
                "test",
                "budget",
                "test",
                "none",
                lambda: BenchmarkObservation(output_bytes=1),
                warmup_iterations=0,
                measured_iterations=2,
            ),
        ),
        run_id="budget-source",
        git_commit="abc123",
    )
    budgets = derive_budgets(run)
    assert verify_budget_source(run, budgets)
    assert budgets.source_run_id == run.run_id
    assert [budget.case_id for budget in budgets.cases] == ["budgeted"]
    assert budgets.cases[0].max_process_peak_rss_bytes is not None

    different_run = run.model_copy(update={"run_id": "different"})
    assert not verify_budget_source(different_run, budgets)

    budget_path = tmp_path / "budgets.json"
    write_budgets(budgets, budget_path)
    assert BenchmarkBudgets.model_validate_json(budget_path.read_text()) == budgets


def test_fresh_run_verification_fails_closed_for_regressions_and_missing_cases() -> None:
    baseline = run_benchmarks(
        (
            BenchmarkCase(
                "budgeted",
                "test",
                "budget",
                "test",
                "none",
                lambda: BenchmarkObservation(output_bytes=1),
                warmup_iterations=0,
                measured_iterations=2,
            ),
        ),
        run_id="budget-source",
        git_commit="abc123",
    )
    budgets = derive_budgets(baseline)
    assert verify_run_against_budgets(baseline, budgets).passed

    budget = budgets.cases[0].model_copy(update={"max_median_ms": 0.000001})
    tight = budgets.model_copy(update={"cases": (budget,)})
    report = verify_run_against_budgets(baseline, tight)
    assert isinstance(report, BenchmarkBudgetReport)
    assert not report.passed
    assert report.violations[0].case_id == "budgeted"
    assert report.violations[0].metric == "median_ms"

    missing = baseline.model_copy(update={"cases": ()})
    report = verify_run_against_budgets(missing, budgets)
    assert not report.passed
    assert report.violations[0].reason.startswith("Budgeted case is missing")


def test_benchmark_iteration_contract_rejects_no_measured_runs() -> None:
    case = BenchmarkCase(
        "invalid",
        "test",
        "invalid",
        "test",
        "none",
        lambda: BenchmarkObservation(),
        measured_iterations=0,
    )
    try:
        run_benchmarks((case,), run_id="invalid", git_commit="abc123")
    except ValueError as error:
        assert "at least one measured run" in str(error)
    else:
        raise AssertionError("invalid benchmark iteration count was accepted")


def test_rss_budget_and_untraced_production_case_fail_closed() -> None:
    run = run_benchmarks(
        (
            BenchmarkCase(
                id="production",
                category="production",
                description="Production wall-clock path",
                implementation="test",
                fixture="fixture",
                operation=lambda: BenchmarkObservation(output_bytes=1),
                warmup_iterations=0,
                measured_iterations=1,
                trace_python_allocations=False,
            ),
        ),
        run_id="rss-source",
        git_commit="abc123",
    )
    assert run.cases[0].peak_python_bytes == 0
    derived = derive_budgets(run)
    case = derived.cases[0].model_copy(update={"max_process_peak_rss_bytes": 1})
    report = verify_run_against_budgets(
        run,
        derived.model_copy(update={"cases": (case,)}),
    )
    assert report.passed is False
    assert report.violations[-1].metric == "process_peak_rss_bytes"


def test_committed_budgets_are_bound_to_a_successful_measured_baseline() -> None:
    run = BenchmarkRun.model_validate_json(
        (ROOT / "benchmarks/results/baseline-2026-09-24-public-fixtures.json").read_text()
    )
    budgets = BenchmarkBudgets.model_validate_json((ROOT / "benchmarks/budgets.json").read_text())

    assert verify_budget_source(run, budgets)
    assert len(run.cases) == 9
    assert all(case.status == BenchmarkStatus.PASSED for case in run.cases)
    assert {budget.case_id for budget in budgets.cases} == {case.id for case in run.cases}
    assert {case.id for case in run.cases} >= {"startup-cold", "openapi-cold"}
    assert "packaging-production-3mf" in {case.id for case in run.cases}


def test_committed_mural_budget_is_bound_to_the_fractional_partition_baseline() -> None:
    run = BenchmarkRun.model_validate_json(
        (ROOT / "benchmarks/results/baseline-2026-07-17-mural-partition.json").read_text()
    )
    budgets = BenchmarkBudgets.model_validate_json(
        (ROOT / "benchmarks/mural-partition-budgets.json").read_text()
    )

    assert verify_budget_source(run, budgets)
    assert len(run.cases) == 1
    case = run.cases[0]
    budget = budgets.cases[0]
    assert case.id == "mural-topology-partition-1024-3x2"
    assert case.status == BenchmarkStatus.PASSED
    assert case.median_ms is not None and case.median_ms <= 15_000
    assert case.process_peak_rss_bytes is not None
    assert budget.max_process_peak_rss_bytes == 300 * 1024 * 1024
    assert case.process_peak_rss_bytes <= budget.max_process_peak_rss_bytes
    assert verify_run_against_budgets(run, budgets).passed
