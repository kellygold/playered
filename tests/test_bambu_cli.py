def test_preparation_preserves_unused_palette_slots(tmp_path):
    input_path = source(tmp_path, extruders=3)
    palette = ["#112233", "#445566", "#778899"]
    with zipfile.ZipFile(input_path, "w") as archive:
        archive.writestr(
            "Metadata/project_settings.config",
            json.dumps(
                {
                    "filament_settings_id": ["PLA"] * 3,
                    "filament_colour": palette,
                }
            ),
        )
    action = (
        PREPARE_EDITABLE.replace(
            'assert "--load-filaments" in arguments',
            'assert "--load-filaments" in arguments\n'
            '    assert arguments[arguments.index("--filament-colour") + 1] == '
            '"#112233;#445566;#778899"',
        )
        .replace('["#FFFFFF"]', repr(palette))
        .replace('["PLA"]', '["PLA"] * 3')
    )
    executable = fake_bambu(tmp_path, "unused-slot", action + VALID_SLICE)
    result = validator(tmp_path, executable).validate(
        input_path,
        profiles=pinned_profiles(tmp_path, filaments=3),
        project_output=tmp_path / "download.3mf",
    )
    assert result.status == BambuValidationStatus.VALIDATED
