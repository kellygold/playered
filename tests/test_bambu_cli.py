def test_cancel_terminates_slice_and_prelaunch_cancel_runs_no_slice(tmp_path) -> None:
    executable = fake_bambu(tmp_path, "cancel", "time.sleep(10)")
    instance = validator(tmp_path, executable)

    already_canceled = CancellationToken()
    already_canceled.cancel()
    with pytest.raises(BambuStudioCanceledError) as prelaunch:
        instance.validate(
            source(tmp_path),
            profiles=pinned_profiles(tmp_path),
            cancellation=already_canceled,
        )
    assert prelaunch.value.result.return_code is None
    assert prelaunch.value.result.command == ()
    assert not executable.with_suffix(".version-probes").exists()

    token = CancellationToken()
    timer = threading.Timer(0.05, token.cancel)
    timer.start()
    try:
        with pytest.raises(BambuStudioCanceledError) as raised:
            instance.validate(
                source(tmp_path), profiles=pinned_profiles(tmp_path), cancellation=token
            )
    finally:
        timer.cancel()
    assert raised.value.result.status == BambuValidationStatus.CANCELED
    assert raised.value.result.canceled
    assert not raised.value.result.timed_out


