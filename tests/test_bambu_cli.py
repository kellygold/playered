def test_profiles_are_required_and_missing_or_changed_pins_fail_before_slice(tmp_path) -> None:
    executable = fake_bambu(tmp_path, "profiles", VALID_SLICE)
    instance = validator(tmp_path, executable)
    project = source(tmp_path)

    with pytest.raises(BambuStudioProfileError, match="requires pinned") as absent:
        instance.validate(project)
    assert absent.value.result.status == BambuValidationStatus.PROFILE_ERROR
    assert absent.value.result.command == ()

    missing = pinned_profiles(tmp_path, prefix="missing")
    missing.machine.path.unlink()
    with pytest.raises(BambuStudioProfileError, match="missing or not a file") as missing_error:
        instance.validate(project, profiles=missing)
    assert missing_error.value.result.return_code is None

    changed = pinned_profiles(tmp_path, prefix="changed")
    changed.process.path.write_text('{"type":"changed"}', encoding="utf-8")
    with pytest.raises(BambuStudioProfileError, match="fingerprint mismatch") as mismatch:
        instance.validate(project, profiles=changed)
    assert mismatch.value.result.status == BambuValidationStatus.PROFILE_ERROR
    assert mismatch.value.result.profiles[-1].role == "process"
    assert (
        mismatch.value.result.profiles[-1].expected_sha256
        != mismatch.value.result.profiles[-1].actual_sha256
    )

    wrong_role = pinned_profiles(tmp_path, prefix="wrong-role")
    wrong_role = BambuSliceProfiles(
        machine=PinnedBambuProfile.pin(wrong_role.process.path),
        process=wrong_role.process,
        filaments=wrong_role.filaments,
    )
    with pytest.raises(BambuStudioProfileError, match="machine profile declares type 'process'"):
        instance.validate(project, profiles=wrong_role)


