def fake_bambu(tmp_path: Path, name: str, action: str) -> Path:
    executable = tmp_path / name
    executable.write_text(
        """#!/usr/bin/env python3
import sys
import time
import zipfile
from pathlib import Path

if "--version" in sys.argv:
    with Path(__file__).with_suffix(".version-probes").open("a", encoding="utf-8") as marker:
        marker.write("probe\\n")
    print("BambuStudio-2.7.1.50")
    raise SystemExit(1)

arguments = sys.argv[1:]
output_directory = Path(arguments[arguments.index("--outputdir") + 1])
output_name = arguments[arguments.index("--export-3mf") + 1]
output_path = output_directory / output_name

ACTION
""".replace("ACTION", action),
        encoding="utf-8",
    )
    executable.chmod(0o755)
    return executable


VALID_SLICE = r"""
with zipfile.ZipFile(output_path, "w") as archive:
    archive.writestr(
        "Metadata/plate_1.gcode",
        "; generated by BambuStudio\nG90\nM83\nG1 X1.0 Y2.0 E0.125\n",
    )
print("slice complete")
print("diagnostic stderr", file=sys.stderr)
"""


def validator(tmp_path: Path, executable: Path, *, timeout: float = 2) -> BambuStudioCliValidator:
    runner = ToolRunner(temp_root=tmp_path / "runs")
    spec = ToolSpec(
        id=ToolId.BAMBU_STUDIO,
        name="Bambu Studio",
        purpose="3MF slice validation",
        candidates=(str(executable),),
        version_arguments=("--version",),
        version_pattern=r"BambuStudio-(\d+(?:\.\d+)+)",
        minimum_version=(2, 0),
        allow_nonzero_version_probe=True,
    )
    registry = ExternalToolRegistry(
        runner=runner,
        specs={ToolId.BAMBU_STUDIO: spec},
        # Process launch can briefly exceed one second on a busy macOS host during the
        # complete suite; the fake probe itself returns immediately once scheduled.
        version_timeout_seconds=3,
    )
    return BambuStudioCliValidator(
        runner=runner,
        registry=registry,
        timeout_seconds=timeout,
    )


def source(tmp_path: Path, payload: bytes = b"project", *, extruders: int = 1) -> Path:
    path = tmp_path / "source project;$(unsafe).3mf"
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr(
            "Metadata/project_settings.config",
            '{"filament_settings_id":['
            + ",".join(f'"filament-{index}"' for index in range(extruders))
            + "]}",
        )
        archive.writestr("Metadata/source-proof.bin", payload)
    return path


def pinned_profiles(
    tmp_path: Path,
    *,
    filaments: int = 1,
    prefix: str = "profile;$(safe)",
) -> BambuSliceProfiles:
    profile_directory = tmp_path / prefix
    profile_directory.mkdir(exist_ok=True)
    machine = profile_directory / "machine profile.json"
    process = profile_directory / "process profile.json"
    machine.write_text('{"type":"machine"}', encoding="utf-8")
    process.write_text('{"type":"process"}', encoding="utf-8")
    filament_paths = []
    for index in range(1, filaments + 1):
        path = profile_directory / f"filament {index}.json"
        path.write_text(f'{{"type":"filament","index":{index}}}', encoding="utf-8")
        filament_paths.append(path)
    return BambuSliceProfiles(
        machine=PinnedBambuProfile.pin(machine),
        process=PinnedBambuProfile.pin(process),
        filaments=tuple(PinnedBambuProfile.pin(path) for path in filament_paths),
    )


def test_success_uses_safe_argument_array_and_retains_slice_evidence(tmp_path) -> None:
    marker = tmp_path / "unsafe"
    executable = fake_bambu(tmp_path, "Bambu Studio fake", VALID_SLICE)
    project = source(tmp_path)
    profiles = pinned_profiles(tmp_path)

    result = validator(tmp_path, executable).validate(project, profiles=profiles)

    assert result.status == BambuValidationStatus.VALIDATED
    assert result.executable == executable.resolve()
    assert result.version == "2.7.1.50"
    assert result.return_code == 0
    assert result.stdout == "slice complete\n"
    assert result.stderr == "diagnostic stderr\n"
    assert not result.timed_out
    assert not result.canceled
    assert result.warnings == ()
    source_sha256 = hashlib.sha256(project.read_bytes()).hexdigest()
    assert result.source_sha256 == source_sha256
    assert result.command[0] == str(executable.resolve())
    assert result.command[1] == "--load-settings"
    assert result.command[3] == "--load-filaments"
    assert "--no-check" in result.command
    arrange_index = result.command.index("--arrange")
    assert result.command[arrange_index : arrange_index + 2] == ("--arrange", "0")
    slice_index = result.command.index("--slice")
    assert arrange_index < slice_index
    assert result.command[slice_index : slice_index + 4] == ("--slice", "0", "--debug", "2")
    assert result.command[2].count(";") == 1
    assert ";$(safe)" not in result.command[2]
    assert ";$(safe)" not in result.command[4]
    assert result.command[-1].endswith(f"input-{source_sha256[:24]}.3mf")
    assert "source project;$(unsafe).3mf" not in result.command
    assert not marker.exists()
    assert result.artifact is not None
    assert result.artifact.name.endswith(".gcode.3mf")
    assert result.artifact.gcode_members == ("Metadata/plate_1.gcode",)
    assert result.artifact.uncompressed_gcode_bytes > 0
    assert len(result.artifact.plates) == 1
    assert result.artifact.plates[0].has_extrusion is True
    assert result.report is not None
    assert result.report.raw_logs.stdout == "slice complete\n"
    assert result.report.raw_logs.stderr == "diagnostic stderr\n"
    assert len(result.artifact.sha256) == 64
    assert [item.role for item in result.profiles] == ["machine", "process", "filament"]
    assert all(item.expected_sha256 == item.actual_sha256 for item in result.profiles)
    assert result.profile_set_sha256 is not None
    assert len(result.profile_set_sha256) == 64
    assert result.cache_key is not None
    assert result.cache_key.startswith("image23mf-bambu-cli-validation-v3:")
    assert list((tmp_path / "runs").iterdir()) == []


